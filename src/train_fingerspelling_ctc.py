# Model
# ---------------------------------------------------------------------------

def build_model(seq_len, feat_dim, vocab_size, lstm1_units, lstm2_units, dropout_rate,
                 normalization_adapt_data=None):
    import keras

    inputs = keras.Input(shape=(seq_len, feat_dim), name="landmark_sequence")
    norm_layer = keras.layers.Normalization(axis=-1, name="input_normalization")
    if normalization_adapt_data is not None:
        norm_layer.adapt(normalization_adapt_data)
    x = norm_layer(inputs)
    x = keras.layers.Bidirectional(
        keras.layers.LSTM(lstm1_units, return_sequences=True), name="bilstm_1"
    )(x)
    x = keras.layers.Dropout(dropout_rate, name="dropout_1")(x)
    x = keras.layers.Bidirectional(
        keras.layers.LSTM(lstm2_units, return_sequences=True), name="bilstm_2"
    )(x)
    x = keras.layers.Dropout(dropout_rate, name="dropout_2")(x)
    logits = keras.layers.Dense(vocab_size, activation=None, name="ctc_logits")(x)

    model = keras.Model(inputs, logits, name="fingerspelling_bilstm_ctc")
    return model


# ---------------------------------------------------------------------------
# CTC loss / decoding helpers (TensorFlow-dependent half; pure-Python half is
# in fingerspelling_ctc_utils.py)
# ---------------------------------------------------------------------------

def compute_ctc_loss(tf, logits, labels, label_lengths, input_lengths):
    loss_per_sample = tf.nn.ctc_loss(
        labels=labels, logits=logits,
        label_length=label_lengths, logit_length=input_lengths,
        logits_time_major=False, blank_index=BLANK_INDEX,
    )
    return tf.reduce_mean(loss_per_sample)


def decode_batch(logits_np):
    """logits_np: (batch, 60, vocab_size) raw numpy array. Returns list of
    decoded label-index lists (one per sample), via greedy argmax decode."""
    preds = np.argmax(logits_np, axis=-1)  # (batch, 60)
    return [greedy_ctc_decode(preds[i]) for i in range(preds.shape[0])]


def evaluate_split(tf, model, X, labels, label_lengths, input_lengths, texts, batch_size=32):
    """Runs the model over X in batches, computes CTC loss and decode-based
    metrics (exact accuracy, CER, WER, predicted/target lengths)."""
    n = X.shape[0]
    all_logits = []
    losses = []
    for start in range(0, n, batch_size):
        end = min(start + batch_size, n)
        batch_logits = model(X[start:end], training=False)
        batch_loss = compute_ctc_loss(
            tf, batch_logits,
            tf.constant(labels[start:end]), tf.constant(label_lengths[start:end]),
            tf.constant(input_lengths[start:end]),
        )
        losses.append(float(batch_loss) * (end - start))
        all_logits.append(batch_logits.numpy())
    logits_np = np.concatenate(all_logits, axis=0)
    mean_loss = sum(losses) / n

    decoded_indices = decode_batch(logits_np)
    predictions = [indices_to_text(d) for d in decoded_indices]

    exact_correct = 0
    cers, wers, pred_lens, target_lens = [], [], [], []
    per_example = []
    for i in range(n):
        target_text = texts[i]
        pred_text = predictions[i]
        is_correct = pred_text == target_text
        exact_correct += int(is_correct)
        cer = character_error_rate(target_text, pred_text)
        wer = word_error_rate(target_text, pred_text)
        cers.append(cer)
        wers.append(wer)
        pred_lens.append(len(pred_text))
        target_lens.append(len(target_text))
        per_example.append({
            "target": target_text, "prediction": pred_text,
            "cer": cer, "wer": wer, "target_len": len(target_text), "pred_len": len(pred_text),
        })

    results = {
        "loss": mean_loss,
        "exact_sequence_accuracy": exact_correct / n,
        "cer_mean": float(np.mean(cers)),
        "wer_mean": float(np.mean(wers)),
        "avg_predicted_length": float(np.mean(pred_lens)),
        "avg_target_length": float(np.mean(target_lens)),
        "n_samples": n,
    }
    return results, per_example


def length_bucket(n):
    if n <= 5:
        return "2-5"
    if n <= 10:
        return "6-10"
    if n <= 15:
        return "11-15"
    return "16+"


def breakdown_by_length(per_example):
    from collections import defaultdict
    buckets = defaultdict(list)
    for ex in per_example:
        buckets[length_bucket(ex["target_len"])].append(ex)
    out = {}
    for bucket, exs in buckets.items():
        out[bucket] = {
            "n": len(exs),
            "exact_sequence_accuracy": sum(1 for e in exs if e["target"] == e["prediction"]) / len(exs),
            "cer_mean": float(np.mean([e["cer"] for e in exs])),
            "wer_mean": float(np.mean([e["wer"] for e in exs])),
        }
    return out


def save_predictions_csv(path, ids, per_example):
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["video_id", "target", "prediction", "cer", "wer", "target_len", "pred_len", "exact_match"])
        for vid, ex in zip(ids, per_example):
            writer.writerow([vid, ex["target"], ex["prediction"], round(ex["cer"], 4), round(ex["wer"], 4),
                              ex["target_len"], ex["pred_len"], ex["target"] == ex["prediction"]])


def save_json(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2, ensure_ascii=False)


