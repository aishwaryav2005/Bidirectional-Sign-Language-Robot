EXPECTED_SHAPE = (config.SEQUENCE_LENGTH, config.FEATURE_VECTOR_LENGTH)  # (60, 147)
MAX_LABEL_LEN = 28  # dataset-wide max character count, confirmed by prior analysis


def set_global_seed(seed):
    os.environ["PYTHONHASHSEED"] = str(seed)
    random.seed(seed)
    np.random.seed(seed)
    try:
        import keras
        keras.utils.set_random_seed(seed)
    except ImportError:
        pass
    try:
        import tensorflow as tf
        tf.config.experimental.enable_op_determinism()
    except (ImportError, AttributeError):
        pass


def refuse_overwrite(path):
    if os.path.exists(path):
        raise FileExistsError(
            f"Refusing to overwrite existing file: {path}. "
            f"Inspect it first; this experiment must not clobber a prior run."
        )


TRAINING_STATE_PATH = os.path.join(MODEL_DIR, "_training_state.json")  # internal, resume bookkeeping only


def save_training_state(epoch, best_val_cer, best_epoch, epochs_without_improvement, history):
    save_json(TRAINING_STATE_PATH, {
        "epoch": epoch, "best_val_cer": best_val_cer, "best_epoch": best_epoch,
        "epochs_without_improvement": epochs_without_improvement, "history": history,
    })


def load_training_state():
    with open(TRAINING_STATE_PATH, encoding="utf-8") as f:
        return json.load(f)


