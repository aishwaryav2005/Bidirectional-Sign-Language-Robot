"""
First baseline experiment for the ISL-Fingerspelling branch: BiLSTM + CTC.

VIDEO (60, 147) -> variable-length character sequence -> text.

Data: data/fingerspelling_processed/ (already preprocessed, read-only here).
Split: data/fingerspelling_processed/splits/{ctc_train,ctc_val}.csv (grouped
by source video, generated by src/generate_fingerspelling_ctc_split.py) for
train/validation, and splits/test.csv (signer_02, 498 samples) as the
LOCKED final test set -- evaluated exactly once, after model selection.

Why a custom training loop instead of model.fit: this project's existing
training scripts (e.g. train_bilstm_baseline.py) use model.fit with a
single (X, y) pair, which fits ordinary classification. CTC needs 4 inputs
per step (logits, labels, input_lengths, label_lengths) and this experiment
specifically wants checkpointing/early-stopping on validation CER (an
edit-distance metric, not a Keras built-in), so a plain tf.GradientTape
loop gives direct, transparent control over exactly those two requirements
while reusing the same keras.Model/Bidirectional-LSTM building blocks as
the rest of this project.

Usage:
    python src/train_fingerspelling_ctc.py --seed 42
"""
