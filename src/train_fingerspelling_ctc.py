def run_smoke_test(tf, model, optimizer, X, labels, label_lengths, input_lengths, batch_size):
    print("-" * 60)
    print("SMOKE TEST")
    print("-" * 60)
    X_batch = X[:batch_size]
    labels_batch = labels[:batch_size]
    label_lengths_batch = label_lengths[:batch_size]
    input_lengths_batch = input_lengths[:batch_size]

    print("Input shape:", X_batch.shape)
    print("Label shape:", labels_batch.shape)
    print("Input lengths:", input_lengths_batch.tolist())
    print("Label lengths:", label_lengths_batch.tolist())

    with tf.GradientTape() as tape:
        logits = model(X_batch, training=True)
        loss = compute_ctc_loss(
            tf, logits, tf.constant(labels_batch), tf.constant(label_lengths_batch),
            tf.constant(input_lengths_batch),
        )
    grads = tape.gradient(loss, model.trainable_variables)
    none_grads = [v.name for g, v in zip(grads, model.trainable_variables) if g is None]
    if none_grads:
        raise RuntimeError(f"SMOKE TEST FAILED: no gradient for variables: {none_grads}")

    loss_value = float(loss.numpy())
    print("Forward pass logits shape:", logits.shape)
    print("CTC loss (pre-update):", loss_value)
    if not np.isfinite(loss_value):
        raise RuntimeError(f"SMOKE TEST FAILED: non-finite loss {loss_value}")
    for g in grads:
        if g is None:
            continue
        g_np = g.numpy() if hasattr(g, "numpy") else np.array(g)
        if not np.all(np.isfinite(g_np)):
            raise RuntimeError("SMOKE TEST FAILED: non-finite gradient detected")

    optimizer.apply_gradients(zip(grads, model.trainable_variables))

    # verify the update actually changed something and still produces a finite loss
    logits2 = model(X_batch, training=False)
    loss2 = compute_ctc_loss(
        tf, logits2, tf.constant(labels_batch), tf.constant(label_lengths_batch),
        tf.constant(input_lengths_batch),
    )
    loss2_value = float(loss2.numpy())
    print("CTC loss (post-update):", loss2_value)
    if not np.isfinite(loss2_value):
        raise RuntimeError(f"SMOKE TEST FAILED: non-finite loss after update {loss2_value}")

    print("SMOKE TEST PASSED.")
    print("-" * 60)


