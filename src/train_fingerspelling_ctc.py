def load_split(csv_path, metadata):
    with open(csv_path, newline="", encoding="utf-8") as f:
        ids = [row["video_id"] for row in csv.DictReader(f)]

    n = len(ids)
    X = np.zeros((n,) + EXPECTED_SHAPE, dtype=np.float32)
    labels = np.zeros((n, MAX_LABEL_LEN), dtype=np.int32)
    label_lengths = np.zeros((n,), dtype=np.int32)
    texts = []

    for i, vid in enumerate(ids):
        row = metadata[vid]
        seq_path = os.path.join(config.PROJECT_ROOT, row["sequence_path"])
        arr = np.load(seq_path)
        if arr.shape != EXPECTED_SHAPE:
            raise ValueError(f"{vid}: expected shape {EXPECTED_SHAPE}, got {arr.shape}")
        X[i] = arr

        char_seq = json.loads(row["char_sequence_json"])
        encoded = encode_char_sequence(char_seq)
        if len(encoded) > MAX_LABEL_LEN:
            raise ValueError(f"{vid}: {len(encoded)} characters exceeds MAX_LABEL_LEN={MAX_LABEL_LEN}")
        labels[i, : len(encoded)] = encoded
        label_lengths[i] = len(encoded)
        texts.append(row["full_text"])

    input_lengths = np.full((n,), config.SEQUENCE_LENGTH, dtype=np.int32)
    return ids, X, labels, label_lengths, input_lengths, texts


